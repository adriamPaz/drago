package com.dragonlandia.model;

/**
 * Enumeración que define los tipos de monstruos disponibles en el juego.
 * Cada tipo tiene características y modificadores de daño únicos.
 * 
 */
public enum TipoMonstruo {
    /** Ogro: monstruo fuerte con 150% de daño */
    OGRO, 
    
    /** Espectro: monstruo ágil con 50% de daño */
    ESPECTRO, 
    
    /** Troll: monstruo equilibrado con 100% de daño */
    TROLL
}
